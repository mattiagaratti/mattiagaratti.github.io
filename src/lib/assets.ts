import manifest from "./image-manifest.json";

type Entry = { width: number; height: number; variants: Record<string, { src: string; width: number }> };
const images = manifest as Record<string, Entry>;

/** Turns a content path ("images/x.jpg", "documents/a.pdf", "/cv", "https://…") into a usable URL. */
export function href(path: string) {
  if (!path) return path;
  if (/^(https?:|mailto:|tel:|#|\/)/.test(path)) return path;
  return "/" + encodeURI(path);
}

export function isExternal(path: string) {
  return /^https?:/.test(path) || /^documents\//.test(path) || /\.pdf(\?|$)/.test(path);
}

/** Optimized image info generated by scripts/optimize-images.mjs (falls back to the original). */
export function image(path: string) {
  const entry = images[path];
  if (!entry) return { src: href(path), srcSet: undefined, width: undefined, height: undefined };
  const v = Object.values(entry.variants).sort((a, b) => a.width - b.width);
  return {
    src: v[v.length - 1].src,
    srcSet: v.length > 1 ? v.map((x) => `${x.src} ${x.width}w`).join(", ") : undefined,
    width: entry.width,
    height: entry.height,
  };
}

export function backgroundUrl(path: string) {
  return image(path).src;
}
